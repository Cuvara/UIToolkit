namespace Cuvara.UIToolkit.Editor.Figma.Tests
{
    using System;
    using System.Collections.Generic;
    using System.IO;
    using System.Linq;
    using System.Text;
    using Cuvara.UIToolkit.FigmaCore;
    using NUnit.Framework;

    /// <summary>
    /// The token bridge: aliases only, deterministic bytes, a content-gated write, and a warning
    /// for every Figma token the import does not declare.
    /// </summary>
    public class FigmaTokenBridgeTests
    {
        private string tempDir;

        [SetUp]
        public void SetUp()
        {
            this.tempDir = Path.Combine(Path.GetTempPath(), "cuvara-bridge-tests-" + Guid.NewGuid().ToString("N"));
        }

        [TearDown]
        public void TearDown()
        {
            if (Directory.Exists(this.tempDir)) Directory.Delete(this.tempDir, recursive: true);
        }

        private static List<FigmaTokenRole> Roles(params string[] pairs)
        {
            var roles = new List<FigmaTokenRole>();
            for (var i = 0; i < pairs.Length; i += 2) roles.Add(new FigmaTokenRole(pairs[i], pairs[i + 1]));
            return roles;
        }

        private static string[] Codes(FigmaTokenBridgeResult result, FigmaDiagnosticSeverity severity)
        {
            return result.Diagnostics.Where(d => d.Severity == severity).Select(d => d.Code).ToArray();
        }

        [Test]
        public void Build_WritesSortedAliasesInsideRoot_WithExactBytes()
        {
            var result = FigmaTokenBridge.Build("Rpg", Roles(
                "--cuvara-color-surface", "--background-primary",
                "--cuvara-color-primary", "--brand-primary"), null, "bridge.uss");

            const string expected =
                "/* Generated by Cuvara UI Toolkit from the Figma profile \"Rpg\". Do not edit: change the profile and regenerate. */\n"
                + ":root {\n"
                + "    --cuvara-color-primary: var(--brand-primary);\n"
                + "    --cuvara-color-surface: var(--background-primary);\n"
                + "}\n";
            Assert.That(result.Content, Is.EqualTo(expected));
            Assert.That(result.MappedRoles, Is.EqualTo(2));
        }

        [Test]
        public void Build_IsIndependentOfRoleOrder()
        {
            var forward = FigmaTokenBridge.Build("P", Roles("--cuvara-a", "--x", "--cuvara-b", "--y"), null, "f");
            var reverse = FigmaTokenBridge.Build("P", Roles("--cuvara-b", "--y", "--cuvara-a", "--x"), null, "f");
            Assert.That(reverse.Content, Is.EqualTo(forward.Content));
        }

        [Test]
        public void Build_NeverCopiesAValue_OnlyVarReferences()
        {
            var result = FigmaTokenBridge.Build("P", Roles("--cuvara-color-primary", "--brand"), new HashSet<string> { "--brand" }, "f");
            var declarations = result.Content.Split('\n').Where(l => l.TrimStart().StartsWith("--", StringComparison.Ordinal)).ToArray();
            Assert.That(declarations, Has.Length.EqualTo(1));
            Assert.That(declarations[0], Does.Match(@"^\s+--cuvara-[a-z0-9-]+: var\(--[A-Za-z0-9_-]+\);$"));
        }

        [Test]
        public void Build_AddsMissingLeadingDashes_ToTheFigmaToken()
        {
            var result = FigmaTokenBridge.Build("P", Roles("--cuvara-color-primary", "brand-primary"), null, "f");
            Assert.That(result.Content, Does.Contain("--cuvara-color-primary: var(--brand-primary);"));
        }

        [Test]
        public void Build_SkipsAnUnmappedRole_WithAnInfo()
        {
            var result = FigmaTokenBridge.Build("P", Roles("--cuvara-color-primary", "", "--cuvara-color-scrim", "--scrim"), null, "f");
            Assert.That(result.Content, Does.Not.Contain("--cuvara-color-primary"));
            Assert.That(result.TotalRoles, Is.EqualTo(2));
            Assert.That(result.MappedRoles, Is.EqualTo(1));
            Assert.That(Codes(result, FigmaDiagnosticSeverity.Info), Does.Contain(FigmaTokenBridge.CodeRoleUnmapped));
        }

        [Test]
        public void Build_RejectsANonCuvaraRole_AndADuplicate()
        {
            var result = FigmaTokenBridge.Build("P", Roles(
                "--brand-primary", "--x",
                "--cuvara-color-primary", "--first",
                "--cuvara-color-primary", "--second"), null, "f");

            Assert.That(Codes(result, FigmaDiagnosticSeverity.Error),
                Is.EquivalentTo(new[] { FigmaTokenBridge.CodeRoleInvalid, FigmaTokenBridge.CodeRoleDuplicate }));
            Assert.That(result.Content, Does.Contain("var(--first)"));
            Assert.That(result.Content, Does.Not.Contain("--second"));
            Assert.That(result.Content, Does.Not.Contain("--brand-primary"));
        }

        [Test]
        public void Build_RejectsAFigmaTokenThatIsNotACustomPropertyName()
        {
            var result = FigmaTokenBridge.Build("P", Roles("--cuvara-color-primary", "--bad name;"), null, "f");
            Assert.That(Codes(result, FigmaDiagnosticSeverity.Error), Does.Contain(FigmaTokenBridge.CodeFigmaTokenInvalid));
            Assert.That(result.Content, Does.Not.Contain("bad"));
        }

        [Test]
        public void Build_WarnsOnATokenTheImportDoesNotDeclare()
        {
            var known = new HashSet<string> { "--brand-primary" };
            var result = FigmaTokenBridge.Build("P", Roles(
                "--cuvara-color-primary", "--brand-primary",
                "--cuvara-color-surface", "--renamed-in-figma"), known, "f");

            var warnings = result.Diagnostics.Where(d => d.Code == FigmaTokenBridge.CodeFigmaTokenUnknown).ToArray();
            Assert.That(warnings, Has.Length.EqualTo(1));
            Assert.That(warnings[0].Message, Does.Contain("--renamed-in-figma"));
            Assert.That(warnings[0].Severity, Is.EqualTo(FigmaDiagnosticSeverity.Warning));
            Assert.That(result.VerifiedRoles, Is.EqualTo(1));

            // The alias is still written: a token can appear on the next push.
            Assert.That(result.Content, Does.Contain("var(--renamed-in-figma)"));
        }

        [Test]
        public void Build_WarnsOnce_WhenNoTokenListCouldBeRead()
        {
            var result = FigmaTokenBridge.Build("P", Roles("--cuvara-a", "--x", "--cuvara-b", "--y"), null, "f");
            Assert.That(result.Diagnostics.Count(d => d.Code == FigmaTokenBridge.CodeTokensUnverified), Is.EqualTo(1));
            Assert.That(result.Diagnostics.Count(d => d.Code == FigmaTokenBridge.CodeFigmaTokenUnknown), Is.Zero);
        }

        [Test]
        public void Build_WithNoMappedRole_StillProducesAValidEmptyRoot()
        {
            var result = FigmaTokenBridge.Build("P", FigmaTokenBridge.CreateDefaultRoles(), null, "f");
            Assert.That(result.Content, Does.EndWith(":root {\n}\n"));
            Assert.That(Codes(result, FigmaDiagnosticSeverity.Warning), Does.Contain(FigmaTokenBridge.CodeNoRoles));
        }

        [Test]
        public void Build_KeepsAProfileNameFromClosingTheHeaderComment()
        {
            var result = FigmaTokenBridge.Build("evil */ :root { --x: red; } /*", Roles("--cuvara-a", "--x"), null, "f");
            var header = result.Content.Split('\n')[0];
            Assert.That(header.IndexOf("*/", StringComparison.Ordinal), Is.EqualTo(header.Length - 2));
        }

        [Test]
        public void DefaultRoles_AreValidDistinctCuvaraVariables()
        {
            Assert.That(FigmaTokenBridge.DefaultRoles, Has.Count.EqualTo(20));
            Assert.That(FigmaTokenBridge.DefaultRoles, Is.Unique);
            foreach (var role in FigmaTokenBridge.DefaultRoles) Assert.That(role, Does.Match("^--cuvara-[a-z0-9-]+$"));

            var result = FigmaTokenBridge.Build("P", FigmaTokenBridge.CreateDefaultRoles(), null, "f");
            Assert.That(result.TotalRoles, Is.EqualTo(20));
            Assert.That(result.Diagnostics.Count(d => d.Severity == FigmaDiagnosticSeverity.Error), Is.Zero);
        }

        [Test]
        public void ParseDeclaredTokens_FindsDeclarations_NotReferencesOrComments()
        {
            const string uss =
                ":root {\n"
                + "    --brand-primary: rgba(1, 2, 3, 1);\n"
                + "    --alias: var(--brand-primary);\n"
                + "    /* --commented-out: 4px; */\n"
                + "}\n"
                + ".x { color: var(--only-used); }\n";

            var tokens = FigmaTokenBridge.ParseDeclaredTokens(uss);
            Assert.That(tokens, Is.EquivalentTo(new[] { "--brand-primary", "--alias" }));
        }

        [Test]
        public void ParseDeclaredTokens_IgnoresDeclarationTextInsideQuotedStrings()
        {
            const string uss =
                ":root {\n"
                + "    --real: 4px;\n"
                + "    content: \"--fake: 1px;\";\n"
                + "    --label: '--also-fake: 2px';\n"
                + "}\n";

            var tokens = FigmaTokenBridge.ParseDeclaredTokens(uss);
            Assert.That(tokens, Is.EquivalentTo(new[] { "--real", "--label" }));
        }

        [Test]
        public void ParseDeclaredTokens_OfNothing_IsEmpty()
        {
            Assert.That(FigmaTokenBridge.ParseDeclaredTokens(null), Is.Empty);
            Assert.That(FigmaTokenBridge.ParseDeclaredTokens(string.Empty), Is.Empty);
        }

        [Test]
        public void NormalizeToken_Works()
        {
            Assert.That(FigmaTokenBridge.NormalizeToken(" brand "), Is.EqualTo("--brand"));
            Assert.That(FigmaTokenBridge.NormalizeToken("--brand"), Is.EqualTo("--brand"));
            Assert.That(FigmaTokenBridge.NormalizeToken("   "), Is.Empty);
            Assert.That(FigmaTokenBridge.NormalizeToken(null), Is.Empty);
        }

        [Test]
        public void WriteIfChanged_WritesOnce_ThenSkips_AndUsesUtf8WithoutBom()
        {
            var path = Path.Combine(this.tempDir, "Theme", FigmaPaths.BridgeFileName);
            var content = FigmaTokenBridge.Build("P", Roles("--cuvara-a", "--x"), null, path).Content;

            Assert.That(FigmaTokenBridge.WriteIfChanged(path, content), Is.True, "first write creates the file and its folder");
            var stamp = File.GetLastWriteTimeUtc(path);
            Assert.That(FigmaTokenBridge.WriteIfChanged(path, content), Is.False, "identical bytes must not be rewritten");
            Assert.That(File.GetLastWriteTimeUtc(path), Is.EqualTo(stamp));

            var bytes = File.ReadAllBytes(path);
            Assert.That(bytes.Take(3), Is.Not.EqualTo(new byte[] { 0xEF, 0xBB, 0xBF }));
            Assert.That(Encoding.UTF8.GetString(bytes), Does.Not.Contain("\r"));
        }

        [Test]
        public void CompareWithDisk_ReportsMissingFreshAndStale()
        {
            var path = Path.Combine(this.tempDir, FigmaPaths.BridgeFileName);
            var v1 = FigmaTokenBridge.Build("P", Roles("--cuvara-a", "--x"), null, path).Content;
            var v2 = FigmaTokenBridge.Build("P", Roles("--cuvara-a", "--y"), null, path).Content;

            Assert.That(FigmaTokenBridge.CompareWithDisk(path, v1), Is.EqualTo(FigmaBridgeFreshness.Missing));
            FigmaTokenBridge.WriteIfChanged(path, v1);
            Assert.That(FigmaTokenBridge.CompareWithDisk(path, v1), Is.EqualTo(FigmaBridgeFreshness.Fresh));
            Assert.That(FigmaTokenBridge.CompareWithDisk(path, v2), Is.EqualTo(FigmaBridgeFreshness.Stale));
            Assert.That(FigmaTokenBridge.WriteIfChanged(path, v2), Is.True);
        }
    }
}
