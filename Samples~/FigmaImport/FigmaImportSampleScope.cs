namespace Cuvara.UIToolkit.Samples.FigmaImport
{
    using System;
    using System.Collections.Generic;
    using Cuvara.UIToolkit.Core;
    using Cuvara.UIToolkit.Flow;
    using Cuvara.UIToolkit.Managers;
    using Cuvara.UIToolkit.Theme;
    using Cuvara.UIToolkit.VContainer;
    using Cysharp.Threading.Tasks;
    using global::VContainer;
    using global::VContainer.Unity;
    using UnityEngine;
    using UnityEngine.UIElements;

    // A MonoBehaviour must live in a file named after it: Unity maps one MonoScript per file
    // by file name, and a scene component whose class lives elsewhere loads as a missing script.

    /// <summary>
    /// The sample's composition root: the package, the asset loader, the ShopCard screen, and
    /// the sheets the theme is built from.
    /// </summary>
    public sealed class FigmaImportSampleScope : LifetimeScope
    {
        [SerializeField] private FigmaSampleAssetLoader loader = new FigmaSampleAssetLoader();

        [SerializeField] private FigmaSampleThemeSheets themeSheets = new FigmaSampleThemeSheets();

        protected override void Configure(IContainerBuilder builder)
        {
            builder.RegisterUIToolkit();                                   // RootUIDocument, view factory, ICuvaraThemeService
            builder.RegisterInstance<IVisualTreeAssetLoader>(this.loader); // key -> imported UXML
            builder.RegisterScreenFlow();                                  // navigator, registry, scope factory

            // The screen generated by Create Screen > Existing UXML, registered exactly as the
            // generated comment says.
            builder.RegisterScreen<ShopCardPresenter, ShopCardView>(ShopCardView.AssetKey);

            builder.RegisterInstance(this.themeSheets);
            builder.Register(resolver => new FigmaModeSwitcher(
                    resolver.Resolve<ICuvaraThemeService>(), this.themeSheets.Light, this.themeSheets.Dark),
                Lifetime.Singleton);

            // One toast stack for the whole sample, in the overlay layer above every screen.
            builder.Register<FigmaSampleToasts>(Lifetime.Singleton);

            builder.RegisterEntryPoint<FigmaImportSampleBootstrap>();
        }
    }

    /// <summary>One <see cref="ToastService"/> in the overlay layer, created on first use.</summary>
    /// <remarks>
    /// Lazy on purpose. The container is built in the scope's <c>Awake</c>, and
    /// <c>UIDocument</c> builds its root in its own <c>OnEnable</c>, in no defined order. A
    /// <c>ToastService</c> built with the container could find no overlay element yet.
    /// </remarks>
    public sealed class FigmaSampleToasts : IDisposable
    {
        private readonly RootUIDocument document;
        private ToastService service;

        public FigmaSampleToasts(RootUIDocument document)
        {
            this.document = document;
        }

        public void Show(string message, float duration, ToastType type)
        {
            this.service ??= new ToastService(this.document.RootUIOverlayElement);
            this.service.Show(message, duration, type);
        }

        public void Dispose()
        {
            this.service?.Dispose();
            this.service = null;
        }
    }

    /// <summary>
    /// The connector's token and mode sheets plus the game's bridge sheet, assigned in the
    /// inspector.
    /// </summary>
    /// <remarks>
    /// Order matters and is applied by <see cref="FigmaImportSampleBootstrap"/>: overrides are
    /// <c>tokens.uss</c> then <c>cuvara-theme-bridge.uss</c>, so the bridge's
    /// <c>var(--token)</c> aliases resolve at the document root; the mode sheet comes last.
    /// The same can be done with no code through <c>RootUIDocument</c>'s Theme Overrides and
    /// Theme Mode Sheet fields.
    /// </remarks>
    [Serializable]
    public sealed class FigmaSampleThemeSheets
    {
        [Tooltip("The connector's tokens.uss (ConnectorOutput/tokens.uss).")]
        public StyleSheet Tokens;

        [Tooltip("The game-owned bridge (Theme/cuvara-theme-bridge.uss), generated from ShopFigmaProfile.")]
        public StyleSheet Bridge;

        [Tooltip("The connector's light mode sheet (ConnectorOutput/light.uss). Initial mode.")]
        public StyleSheet Light;

        [Tooltip("The connector's dark mode sheet (ConnectorOutput/dark.uss).")]
        public StyleSheet Dark;
    }

    /// <summary>A dictionary of UXML assigned in the inspector: the whole of <see cref="IVisualTreeAssetLoader"/>.</summary>
    /// <remarks>
    /// A game usually points its loader at Addressables. Either way the key is
    /// <c>ShopCardView.AssetKey</c> and the asset is the connector's <c>ShopCard.uxml</c>,
    /// referenced where the connector wrote it, never copied.
    /// </remarks>
    [Serializable]
    public sealed class FigmaSampleAssetLoader : IVisualTreeAssetLoader
    {
        [SerializeField] private List<Entry> entries = new List<Entry>();

        [Serializable]
        public sealed class Entry
        {
            public string          Key;
            public VisualTreeAsset Asset;
        }

        public UniTask<VisualTreeAsset> LoadAsync(string key)
        {
            foreach (var entry in this.entries)
            {
                if (entry.Key == key && entry.Asset != null) return UniTask.FromResult(entry.Asset);
            }

            var known = string.Join(", ", this.entries.ConvertAll(e => e.Key));
            throw new KeyNotFoundException($"No UXML registered for key '{key}'. Registered keys: {known}.");
        }
    }
}
